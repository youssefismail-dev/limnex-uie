"""DC1 -- verify before anything is scored (PREREG_DC1.md section 4, K0).

    V1 files      every registered file for the modes the notebook ran: n, sha256
                  and seed as PROVENANCE records; the settings each was made with
                  equal generation_kwargs(settings) in the DC1 arm and nothing in
                  the base arm; the checkpoint, the settings file and a code
                  bundle that matched its manifest, from a commit in this history;
                  no other files
    V2 states     every controlled URL is in its state
    V3 identity   at least 250 URLs per mode regenerated byte-identically on this
                  CPU with DC1's settings (free: benign and phishing g0; control:
                  benign P1Q1 and phishing P1Q0 g0 -- blend included)
    V4 scorer     cr1_score's canonical scoring reproduces HC1 C2's published E7
                  free-mode record from its stored generations, both classes

    python research/dc1/dc1_verify.py --dc1 data/dc1 --bundle data/bundle2 \
        --checkpoint data/best_e7.pt
"""
import argparse
import collections
import hashlib
import json
import random
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "cr1"))

from dc1_common import (FROZEN_DELTA, G, MEASURABLE, N_CTRL, N_FREE, STATES,  # noqa: E402
                        generation_kwargs, seed_ctrl, seed_free)

IDENTITY_MIN = 250
STATE_OF = {s: (v["PTH"], v["QRY"]) for s, v in STATES.items()}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def is_ancestor(commit: str) -> bool:
    return bool(commit) and subprocess.run(
        ["git", "merge-base", "--is-ancestor", commit, "HEAD"],
        cwd=ROOT, capture_output=True).returncode == 0


def expected_jobs(settings: dict) -> list:
    """The notebook's job list, rebuilt from the same settings (DC1_generate.ipynb cell 3)."""
    free_on = any(generation_kwargs(settings, lab, "free") for lab in ("benign", "phishing"))
    ctrl_on = any(generation_kwargs(settings, lab, st) for lab, sts in MEASURABLE.items() for st in sts)
    jobs = []
    if free_on:
        jobs += [dict(mode="free", arm=arm, label=lab, state=None, g=g, seed=seed_free(lab, g),
                      file=f"free_{arm}_{lab}_g{g}.json")
                 for arm in ("base", "dc1") for lab in ("benign", "phishing") for g in range(G)]
    if ctrl_on:
        jobs += [dict(mode="control", arm="dc1", label=lab, state=st, g=g, seed=seed_ctrl(lab, st, g),
                      file=f"ctrl_dc1_{lab}_{st}_g{g}.json")
                 for lab, sts in MEASURABLE.items() for st in sts for g in range(G)]
        jobs += [dict(mode="control", arm="base", label=lab, state=st, g=0, seed=seed_ctrl(lab, st, 0),
                      file=f"ctrl_base_{lab}_{st}_g0.json")
                 for lab, sts in MEASURABLE.items() for st in sts]
    return jobs


def in_state(url, state: str) -> bool:
    from uie.evaluation import FIELDS
    p, q = STATE_OF[state]
    return bool(FIELDS["PTH"](url)) == p and bool(FIELDS["QRY"](url)) == q


def _placement(table, label, n, seed):
    """The suffix groups and the final shuffle both generation paths apply."""
    rng = random.Random(seed)
    drawn = table.sample(label, n, rng)
    perm = list(range(n))
    rng.shuffle(perm)
    where = {orig: pos for pos, orig in enumerate(perm)}
    groups = sorted(collections.Counter(zip(["domain"] * n, drawn)).items())
    return groups, where


def identity(model, tok, table, urls, label, seed, extra, budget, state=None):
    """Regenerate leading suffix groups on this CPU. Free (state None): every URL
    of a group sits in the group's block. Held control: the group's first-pass
    URLs that honour the state lead its block (CR1's rule)."""
    import torch
    from uie.model import generate
    groups, where = _placement(table, label, len(urls), seed)
    start = same = compared = 0
    for i, ((frame, suffix), count) in enumerate(groups):
        if compared >= budget:
            break
        got = generate(model, tok, label=label, n=count, suffix=suffix, decoder="temperature",
                       seed=seed + i, frame=frame, batch_size=32, device=torch.device("cpu"),
                       field_bias={"PTH": {tok.eos_id: -FROZEN_DELTA[label]}},
                       decoder_kwargs={"temperature": 1.0},
                       fields=None if state is None else dict(STATES[state]), **extra)
        keep = [u for u in got if state is None or in_state(u, state)]
        for rank, u in enumerate(keep):
            same += urls[where[start + rank]] == u
            compared += 1
        start += count
    return same, compared


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dc1", type=Path, required=True)
    ap.add_argument("--bundle", type=Path, required=True)
    ap.add_argument("--checkpoint", type=Path, required=True)
    ap.add_argument("--skip-v4", action="store_true", help="simulation only")
    args = ap.parse_args()

    import torch
    from uie.controlled import StateSuffixTables
    from uie.suffixes import SuffixTable
    from uie.train import load_checkpoint

    gens = args.dc1 / "gen"
    prov = json.loads((gens / "PROVENANCE.json").read_text(encoding="utf-8"))
    settings = json.loads((args.dc1 / "settings.json").read_text(encoding="utf-8"))
    by_file = {r["file"]: r for r in prov["files"]}
    failures = []

    # V1 -- provenance level
    if prov["checkpoint"]["sha256"] != sha256(args.checkpoint):
        failures.append("V1: checkpoint differs from the local file")
    if prov["settings_sha256"] != sha256(args.dc1 / "settings.json"):
        failures.append("V1: settings differ from data/dc1/settings.json")
    if prov.get("code_integrity", {}).get("mismatched") != []:
        failures.append("V1: the code bundle did not match its manifest on the GPU")
    if not is_ancestor(prov.get("code_commit", "")):
        failures.append(f"V1: code commit {prov.get('code_commit')!r} is not in this history")
    jobs = expected_jobs(settings)
    names = {j["file"] for j in jobs}
    extra = sorted(p.name for p in gens.glob("*.json") if p.name != "PROVENANCE.json" and p.name not in names)
    if extra:
        failures.append(f"V1: unregistered files {extra}")

    files = {}
    for j in jobs:
        p, rec = gens / j["file"], by_file.get(j["file"]) or {}
        if not p.is_file():
            failures.append(f"V1: {j['file']} missing ({rec.get('error')})")
            continue
        urls = json.loads(p.read_text(encoding="utf-8"))
        want_n = N_FREE[j["label"]] if j["mode"] == "free" else N_CTRL
        want_kw = generation_kwargs(settings, j["label"], j["state"] or "free") if j["arm"] == "dc1" else {}
        if len(urls) != want_n:
            failures.append(f"V1: {j['file']} has {len(urls)} urls, registered {want_n}")
        if rec.get("sha256") != sha256(p) or rec.get("seed") != j["seed"]:
            failures.append(f"V1: {j['file']} sha256 or seed differs from PROVENANCE")
        if rec.get("settings") != want_kw:
            failures.append(f"V1: {j['file']} was made with settings {rec.get('settings')}, "
                            f"registered {want_kw}")
        if j["mode"] == "control":                                   # V2
            bad = sum(not in_state(u, j["state"]) for u in urls)
            if bad:
                failures.append(f"V2: {j['file']} has {bad} URLs outside {j['state']}")
        files[j["file"]] = (j, urls)
    print(f"  V1/V2: {len(files)} of {len(jobs)} registered files checked", flush=True)

    # V3 -- byte identity on this CPU, DC1 settings included
    model, tok, _ = load_checkpoint(args.checkpoint, device=torch.device("cpu"))
    model.eval()
    shipped = SuffixTable.load(args.bundle / "suffix_table.json")
    tables = StateSuffixTables.load(ROOT / "data" / "state_suffix_tables.json")
    plan = {"free": [("free_dc1_benign_g0.json", None), ("free_dc1_phishing_g0.json", None)],
            "control": [("ctrl_dc1_benign_P1Q1_g0.json", "P1Q1"),
                        ("ctrl_dc1_phishing_P1Q0_g0.json", "P1Q0")]}
    ident = {}
    for mode, targets in plan.items():
        todo = [(f, st) for f, st in targets if f in files]
        if not todo:
            continue
        same = compared = 0
        for f, st in todo:
            j, urls = files[f]
            table = shipped if st is None else tables.for_state(j["label"], STATES[st])
            s, c = identity(model, tok, table, urls, j["label"], j["seed"],
                            generation_kwargs(settings, j["label"], st or "free"),
                            -(-IDENTITY_MIN // len(todo)), state=st)
            same, compared = same + s, compared + c
            print(f"  V3 identity {f:<34} {s}/{c}", flush=True)
        ident[mode] = {"compared": compared, "identical": same}
        if compared < IDENTITY_MIN or same != compared:
            failures.append(f"V3: {mode} identity {same}/{compared}")

    # V4 -- the free-mode scorer reproduces a published record from its own inputs
    v4 = {}
    if not args.skip_v4:
        from cr1_score import pools, score
        for label in ("benign", "phishing"):
            published = json.loads((ROOT / "data" / f"hc1_c2_e7_{label}" / "eval_report.json")
                                   .read_text(encoding="utf-8"))[label]["fields"]
            src = sorted((ROOT / "data" / "gen_cache_e7_gpu").glob(f"*_{label}_n8000_*.json"))
            fields, _ = score(pools(args.bundle, label), [json.loads(p.read_text(encoding="utf-8"))
                                                          for p in src], 8000)
            def x_of(row):
                x = (row or {}).get("acceptance", {}).get("x")
                return None if x is None or x != x else float(x)      # NaN -> None

            diffs = {}
            for f in published:
                a, b = x_of(fields.get(f)), x_of(published[f])
                diffs[f] = 0.0 if a is None and b is None else (
                    float("inf") if a is None or b is None else abs(a - b))
            v4[label] = diffs
            worst = max(diffs.values())
            print(f"  V4 scorer {label:<9} max |x - published| {worst:.2e}", flush=True)
            if worst > 1e-9:
                failures.append(f"V4: {label} scorer differs from HC1 C2's record by {worst:.2e}")

    verdict = "PASS" if not failures else "FAIL"
    (args.dc1 / "VERIFY.json").write_text(json.dumps(
        {"registration": "research/dc1/PREREG_DC1.md", "identity": ident, "v4": v4,
         "failures": failures, "verdict": verdict}, indent=1), encoding="utf-8")
    print("failures:", failures or "none")
    print("VERIFY:", verdict)


if __name__ == "__main__":
    main()
