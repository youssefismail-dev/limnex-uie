"""E11 -- constants and the generation calls shared by the Kaggle notebooks and the
laptop tools, so every one of them makes exactly the same calls
(research/native/PREREG_E11.md sections 1-2).

Four arms from one shared start, trained in one session; each adds one change to
the arm it is measured against:

    e11_rs     the root slash                     against e10_base (E10)
    e11_ref    + the clipping repair              against e11_rs
    e11_joint  + joint control dropout            against e11_ref
    e11_plan   the plan (+ slash + repair); free mode's plan supplied from the
               data (D6)                          against e11_ref

All four use the baseline's raw decode. Nothing is resampled, rejected or masked:
the supplied plan is control mode's native conditioning, fed the data's presence
state for the drawn suffix, exactly as the suffix itself is fed.
"""
from __future__ import annotations

import collections
import random
from typing import Dict, List, Mapping, Optional

from e8_common import (G, LABELS, N_FREE, STATES, UNMEASURABLE, n_ctrl,  # noqa: F401
                       seed_ctrl, seed_free)
from uie.baseline import E9_LN as BASELINE  # this arm is built on e9_ln, not the adopted engine
from uie.suffixes import SuffixTable, generate_with_suffixes

#: The baseline recipe (uie/baseline.py), exactly.
BASE: Dict[str, object] = dict(BASELINE.recipe)
#: D1 + D2: every arm writes the root slash, from the shared start.
SLASH = {"root_slash": True, "shared_start": True}
#: D3: the clip cap after step 1,000 (it is 1.0 before; TrainConfig.grad_clip_switch).
REPAIR = {"grad_clip_late": 5.0}
ARMS: Dict[str, dict] = {
    "e11_rs": {**SLASH},
    "e11_ref": {**SLASH, **REPAIR},
    "e11_joint": {**SLASH, **REPAIR, "field_dropout_joint": True},
    "e11_plan": {**SLASH, **REPAIR, "presence_plan": True, "field_dropout": 0.0},
}
#: Each arm's reference (PREREG_E11 section 0): the arm it adds one change to.
REFERENCE = {"e11_rs": "e10_base", "e11_ref": "e11_rs", "e11_joint": "e11_ref",
             "e11_plan": "e11_ref"}
#: D6: arms whose free mode is given the data's plan.
SUPPLIED = frozenset({"e11_plan"})
#: The presence states in the presence table's order (e11_targets.py).
PRESENCE = ("P0Q0", "P0Q1", "P1Q0", "P1Q1")
#: D6: the seed offset of a state's generation call, clear of generate's seed + i.
STATE_SEED = 10_000_000
#: The E10 start (26926388..., reproduced on Kaggle's torch 2.10), which the
#: shared start's 107-token part must equal (D2, V-id).
E10_START = "26926388bb575e2c9f70f7a611f762b3e53062f58f6638c70d13f0e46f213ad1"


def recipe(arm: str) -> dict:
    """The `uie.kaggle_train.run` arguments for one arm."""
    return {**BASE, **ARMS[arm]}


def decode() -> dict:
    """D7: the baseline's raw decode -- temperature 1.0 and nothing else."""
    return BASELINE.decode_kwargs()


def supplied_tables(presence: Mapping[str, Mapping[str, List[int]]],
                    shipped: Mapping[str, Mapping[str, float]], label: str
                    ) -> Dict[str, Dict[str, float]]:
    """D6: w_k(s) = shipped(s) * n(s, k) / n(s) for each presence state k. Summed
    over s it is the state's share under the shipped table; normalised, it is the
    suffix distribution within the state."""
    n = presence[label]
    out: Dict[str, Dict[str, float]] = {k: {} for k in PRESENCE}
    for s, c in shipped[label].items():
        row = n.get(s)
        if not row:
            raise KeyError(f"{label} suffix {s!r} is in the shipped table but has no "
                           "presence row")
        tot = sum(row)
        for i, k in enumerate(PRESENCE):
            if row[i]:
                out[k][s] = c * row[i] / tot
    return out


def free_urls_supplied(model, tokenizer, label: str, g: int, shipped: SuffixTable,
                       presence, *, device=None, n: int = N_FREE,
                       plan_trace: Optional[list] = None) -> List[str]:
    """D6: FULL FREE with the data's plan. The state counts are one multinomial draw
    at the canonical seed; each state is generated by control mode's native call
    with the state supplied and its suffix drawn from w_k; the URLs are shuffled.
    Equivalent to drawing, URL by URL, the suffix from the shipped table and the
    state from the data's rate for that suffix."""
    tables = supplied_tables(presence, shipped.counts, label)
    weights = [sum(tables[k].values()) for k in PRESENCE]
    rng = random.Random(seed_free(g))
    counts = collections.Counter(rng.choices(PRESENCE, weights=weights, k=n))
    urls: List[str] = []
    for i, k in enumerate(PRESENCE):
        if not counts[k]:
            continue
        urls.extend(generate_with_suffixes(
            model, tokenizer, label=label, n=counts[k],
            table=SuffixTable({label: tables[k]}),
            seed=seed_free(g) + STATE_SEED * (i + 1), device=device,
            fields=dict(STATES[k]), plan_trace=plan_trace, **decode()))
    rng.shuffle(urls)
    return urls


def free_urls(model, tokenizer, arm: str, label: str, g: int, shipped: SuffixTable, *,
              presence=None, device=None, n: int = N_FREE,
              plan_trace: Optional[list] = None) -> List[str]:
    """FULL FREE, canonical seeds: the hidden-control arms run their controls `?`;
    a supplied-plan arm is given the data's plan (D6)."""
    if arm in SUPPLIED:
        if presence is None:
            raise ValueError(f"{arm}'s free mode needs the presence table (D6)")
        return free_urls_supplied(model, tokenizer, label, g, shipped, presence,
                                  device=device, n=n, plan_trace=plan_trace)
    return generate_with_suffixes(model, tokenizer, label=label, n=n, table=shipped,
                                  seed=seed_free(g), device=device, plan_trace=plan_trace,
                                  **decode())


def control_urls(model, tokenizer, label: str, state: str, g: int, state_tables, *,
                 device=None, n: Optional[int] = None,
                 plan_trace: Optional[list] = None) -> List[str]:
    """FULL CONTROL, native: the state's suffix table, the request supplied (prefix
    controls, or the plan), E8's seeds, nothing redrawn."""
    return generate_with_suffixes(model, tokenizer, label=label,
                                  n=n if n is not None else n_ctrl(label, state),
                                  table=state_tables.for_state(label, STATES[state]),
                                  seed=seed_ctrl(label, state, g), device=device,
                                  fields=dict(STATES[state]), plan_trace=plan_trace,
                                  **decode())


def jobs() -> List[dict]:
    """Every file the generation notebook writes (PREREG_E11 D8): 200."""
    out: List[dict] = []
    for arm in ARMS:
        for label in LABELS:
            for g in range(G):
                out.append({"file": f"free_{arm}_{label}_g{g}.json", "arm": arm,
                            "mode": "free", "label": label, "state": None, "g": g,
                            "n": N_FREE, "seed": seed_free(g),
                            "plan": "supplied" if arm in SUPPLIED else "model"})
    for arm in ARMS:
        for label in LABELS:
            for state in STATES:
                for g in range(G):
                    out.append({"file": f"ctrl_{arm}_{label}_{state}_g{g}.json", "arm": arm,
                                "mode": "control", "label": label, "state": state, "g": g,
                                "n": n_ctrl(label, state), "seed": seed_ctrl(label, state, g),
                                "plan": "requested"})
    return out
