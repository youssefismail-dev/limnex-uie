"""
research/d2/verify_engine.py — D2 step 4: the public interface is the adopted engine.

    python research/d2/verify_engine.py

On the real checkpoint (data/e16/train/e16_cap/final.pt), CPU:
  E1  uie.load verifies the published file and e16_b5's weights.
  E2  the packaged decoder (uie.engine.generate_free) returns EXACTLY what the experiment layer
      returns (research/e17/e17_common.py free_urls, B5 on) at E8's canonical free seed, for
      both classes. The experiment layer was itself regenerated byte for byte against the
      published GPU runs (E3_FINAL_REPORT section 6, V2), so this closes the chain.
  E3  the packaged tables are the ones those runs read (sha256).
  E4  with the published Bloom filter, the novelty screen runs on real output (rates reported).
  E5  Engine.score equals the typicality scorer called directly.
Writes research/d2/ENGINE_VERIFY.json. Generation only; nothing is trained.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
for d in ("research/native", "research/e13", "research/e15", "research/e16", "research/e17"):
    sys.path.insert(0, str(ROOT / d))

CKPT = ROOT / "data/e16/train/e16_cap/final.pt"
BLOOM = ROOT / "data/bundle2/known_urls.bloom.gz"
N = 300
OUT = ROOT / "research/d2/ENGINE_VERIFY.json"


def main() -> None:
    import e17_common as E17
    from e8_common import seed_free
    import uie
    from uie.api import ASSET_SHA256, _sha256
    from uie.engine import generate_free
    from uie.suffixes import SuffixTable
    from uie.typicality import TypicalityScorer

    sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
    t0 = time.time()
    res = {"plan": "research/d2/D2_PLAN.md step 4", "n_per_class": N}

    engine = uie.load(CKPT)                                        # E1: raises unless published
    res["E1_load_verified"] = True
    print(f"E1 load + verify: PASS ({time.time() - t0:.0f}s)", flush=True)

    shipped = SuffixTable.load(ROOT / "data/bundle2/suffix_table.json")
    presence_slash = json.loads((ROOT / "data/e12/presence_slash_table.json").read_text(encoding="utf-8"))["table"]
    res["E3_tables"] = {name: _sha256(ROOT / "uie/assets" / name) == sha for name, sha in ASSET_SHA256.items()}
    print(f"E3 packaged tables = published: {res['E3_tables']}", flush=True)

    e2 = {}
    for label in ("benign", "phishing"):
        t1 = time.time()
        research = E17.free_urls(engine.model, engine.tokenizer, label, 0, shipped, presence_slash, b5=True, n=N)
        package = generate_free(engine.model, engine.tokenizer, label=label, n=N, seed=seed_free(0),
                                presence_slash=engine._presence_slash, shipped=engine._shipped)
        e2[label] = {"identical": research == package, "n": len(package), "seconds": round(time.time() - t1)}
        print(f"E2 {label}: packaged decoder == experiment layer: {research == package} "
              f"({len(package)} URLs, {time.time() - t1:.0f}s)", flush=True)
    res["E2_parity"] = e2

    gated = uie.load(CKPT, known_urls=BLOOM)
    kept = gated.generate("phishing", n=N, seed=seed_free(0))
    r = gated.last_report
    res["E4_novelty_screen"] = {"n": r.n_total, "kept": r.n_passed, "removed": dict(r.by_reason),
                                "novelty_checked": gated.novelty_checked}
    print(f"E4 {gated.report_text()}", flush=True)

    urls = package[:50]
    direct = TypicalityScorer(engine.model, engine.tokenizer).score(urls)
    via = engine.score(urls)
    same = all(abs(a["llr"] - b["llr"]) == 0.0 for a, b in zip(direct, via))
    res["E5_score_identical"] = same
    print(f"E5 Engine.score == the typicality scorer: {same}", flush=True)

    res["verdict"] = "PASS" if (all(v["identical"] for v in e2.values()) and all(res["E3_tables"].values())
                               and same and r.n_total == N) else "FAIL"
    OUT.write_text(json.dumps(res, indent=1), encoding="utf-8")
    print(f"VERDICT: {res['verdict']} ({time.time() - t0:.0f}s)", flush=True)
    sys.exit(0 if res["verdict"] == "PASS" else 1)


if __name__ == "__main__":
    main()
